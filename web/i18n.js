let current = "en";

export function detectLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q && D[q]) return q;
  try {
    const saved = localStorage.getItem("nextssr-lang");
    if (saved && D[saved]) return saved;
  } catch (_) { /* storage unavailable */ }
  const nav = (navigator.languages || [navigator.language || "en"]).map((l) => l.slice(0, 2).toLowerCase());
  return nav.find((l) => D[l]) || "en";
}

export function lang() {
  return current;
}

export function t(key, vars = {}) {
  const s = (D[current] && D[current][key]) ?? D.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

export function setLang(l) {
  current = D[l] ? l : "en";
  try { localStorage.setItem("nextssr-lang", current); } catch (_) { /* ignore */ }
  document.documentElement.lang = current === "pt" ? "pt-BR" : current;
  document.title = t("meta.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  document.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
}
